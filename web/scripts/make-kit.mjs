#!/usr/bin/env node
// Builds the test kits to send to testers, one per system, with nothing to install but Chrome:
//
//   ../dist/osa-myo-web-test-mac/      OSA-MYO-Controller-Web.app (Apple Silicon + Intel), guide, report
//   ../dist/osa-myo-web-test-windows/  OSA-MYO-Controller-Web.exe, guide, report
//   and a .zip of each.
//
//   npm run kit            (from web/; needs Deno 2 for `deno compile`; macOS for the .app)
//
// The app is kit/main.mjs (kit/launcher.mjs + the relay + the built page embedded as base64),
// compiled by Deno. The build tag (About, saved logs, VERSIONE.txt) is the git commit, "-dirty"
// when the tree has uncommitted changes, so a tester's log says exactly which code they ran.

import { execFileSync } from "node:child_process";
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const root = path.resolve(web, "..");
const work = path.join(os.tmpdir(), "osa-myo-web-kit-build"); // binaries: keep them out of synced folders
const outRoot = path.join(root, "dist");
const NAME = "OSA-MYO-Controller-Web";
const run = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: "inherit", ...opts });

const git = (...args) => {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
};
const commit = git("rev-parse", "--short", "HEAD") || "nogit";
const dirty = git("status", "--porcelain") ? "-dirty" : "";
const date = new Date().toISOString().slice(0, 10);
const build = `${commit}${dirty} ${date}`;
const { version } = JSON.parse(readFileSync(path.join(web, "package.json"), "utf8"));

try {
  execFileSync("deno", ["--version"], { stdio: "ignore" });
} catch {
  console.error("kit: needs Deno 2 (https://deno.com, or brew install deno) to compile the app");
  process.exit(1);
}

// 1. the page, with the build tag
console.log(`kit: build ${build}`);
run(process.platform === "win32" ? "npm.cmd" : "npm", ["run", "build"], {
  cwd: web, env: { ...process.env, MYO_BUILD: build }, shell: process.platform === "win32",
});

// 2. the page as a module the compiled app embeds
const files = {};
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = path.join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else files[path.relative(path.join(web, "dist"), p).split(path.sep).join("/")] = readFileSync(p).toString("base64");
  }
};
walk(path.join(web, "dist"));
writeFileSync(
  path.join(web, "kit", "app-files.gen.mjs"),
  `// generated by scripts/make-kit.mjs, do not edit\nexport const BUILD = ${JSON.stringify(build)};\nexport const FILES = ${JSON.stringify(files)};\n`,
);

// 3. compile
rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });
// the .exe's icon: the page icon at 256 px (sips is macOS's; elsewhere the .exe gets Deno's icon)
const icon = path.join(work, "icon.ico");
let iconArgs = [];
if (process.platform === "darwin") {
  const png = path.join(work, "icon-256.png");
  execFileSync("sips", ["-z", "256", "256", path.join(web, "public", "icon.png"), "--out", png], { stdio: "ignore" });
  makeIco(png, icon);
  iconArgs = ["--icon", icon];
}
const compile = (target, out, extra = []) =>
  run("deno", ["compile", "-A", "--no-config", "--node-modules-dir=none", "--no-check", "--quiet",
    "--target", target, "--output", out, ...extra, path.join(web, "kit", "main.mjs")]);
compile("aarch64-apple-darwin", path.join(work, "mac-arm64"));
compile("x86_64-apple-darwin", path.join(work, "mac-x64"));
compile("x86_64-pc-windows-msvc", path.join(work, `${NAME}.exe`), ["--no-terminal", ...iconArgs]);

// 4. the kits
const common = (dir) => {
  for (const f of ["GUIDA.md", "RAPPORTO.md"]) copyFileSync(path.join(web, "kit", f), path.join(dir, f));
  mkdirSync(path.join(dir, "extra"), { recursive: true });
  copyFileSync(path.join(root, "examples", "myo_receiver.maxpat"), path.join(dir, "extra", "myo_receiver.maxpat"));
  writeFileSync(path.join(dir, "VERSIONE.txt"), `OSA MYO Controller web ${version}\nbuild ${build}\n\nLeggi GUIDA.md per iniziare.\n`);
};
const zip = (dir) => {
  const z = `${dir}.zip`;
  rmSync(z, { force: true });
  if (process.platform === "win32" || !existsSync("/usr/bin/zip")) {
    console.log(`kit: no zip tool here, zip ${dir} by hand`);
    return;
  }
  // -y keeps the .app's symlinks (none today) and the zip keeps the executable bit
  run("zip", ["-qryX", z, path.basename(dir), "-x", "*.DS_Store"], { cwd: path.dirname(dir) });
  console.log(`kit: ${path.relative(process.cwd(), z)}  (${(statSync(z).size / 1e6).toFixed(0)} MB)`);
};

// macOS: a universal binary in a minimal .app (no Dock icon: it has no window, the page is the UI)
const mac = path.join(outRoot, "osa-myo-web-test-mac");
rmSync(mac, { recursive: true, force: true });
if (process.platform === "darwin") {
  const app = path.join(mac, `${NAME}.app`, "Contents");
  mkdirSync(path.join(app, "MacOS"), { recursive: true });
  mkdirSync(path.join(app, "Resources"), { recursive: true });
  const bin = path.join(app, "MacOS", NAME);
  run("lipo", ["-create", "-output", bin, path.join(work, "mac-arm64"), path.join(work, "mac-x64")]);
  chmodSync(bin, 0o755);
  copyFileSync(path.join(root, "packaging", "OSA-MYO-Controller.icns"), path.join(app, "Resources", "OSA-MYO-Controller.icns"));
  writeFileSync(path.join(app, "Info.plist"), plist({
    CFBundleName: "OSA MYO Controller web",
    CFBundleDisplayName: "OSA MYO Controller web",
    CFBundleIdentifier: "com.oscillacreations.osa-myo-controller.web",
    CFBundleExecutable: NAME,
    CFBundleIconFile: "OSA-MYO-Controller",
    CFBundlePackageType: "APPL",
    CFBundleShortVersionString: version,
    CFBundleVersion: commit,
    LSMinimumSystemVersion: "11.0",
    LSUIElement: true,
    NSHumanReadableCopyright: "© 2026 Daniele Fabris, Simone Arganini · www.oscillacreations.com",
  }));
  const identity = process.env.CODESIGN_IDENTITY;
  run("codesign", ["--force", "--deep", ...(identity ? ["--options", "runtime", "--timestamp"] : []),
    "--sign", identity || "-", path.join(mac, `${NAME}.app`)]);
  common(mac);
  zip(mac);
} else console.log("kit: the macOS app is built on macOS only (lipo, codesign): skipped");

const win = path.join(outRoot, "osa-myo-web-test-windows");
rmSync(win, { recursive: true, force: true });
mkdirSync(win, { recursive: true });
copyFileSync(path.join(work, `${NAME}.exe`), path.join(win, `${NAME}.exe`));
common(win);
zip(win);

rmSync(work, { recursive: true, force: true });

// ------------------------------------------------------------------ helpers
function plist(o) {
  const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;");
  const body = Object.entries(o).map(([k, v]) =>
    `  <key>${k}</key>\n  ${typeof v === "boolean" ? (v ? "<true/>" : "<false/>") : `<string>${esc(v)}</string>`}`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" ` +
    `"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n${body}\n</dict>\n</plist>\n`;
}

/** A Windows .ico holding the PNG itself (Vista+ reads PNG entries); 256 px or less. */
function makeIco(png, out) {
  const data = readFileSync(png);
  const w = data.readUInt32BE(16), h = data.readUInt32BE(20);
  if (w > 256 || h > 256) throw new Error(`${png}: ${w}x${h}, an .ico entry is at most 256x256`);
  const head = Buffer.alloc(22);
  head.writeUInt16LE(0, 0); // reserved
  head.writeUInt16LE(1, 2); // icon
  head.writeUInt16LE(1, 4); // one image
  head.writeUInt8(w === 256 ? 0 : w, 6);
  head.writeUInt8(h === 256 ? 0 : h, 7);
  head.writeUInt16LE(1, 10); // planes
  head.writeUInt16LE(32, 12); // bits
  head.writeUInt32LE(data.length, 14);
  head.writeUInt32LE(22, 18);
  writeFileSync(out, Buffer.concat([head, data]));
}
